  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await phone.waitForFunction(previous => document.querySelector('.canvas-host canvas')?.toDataURL() !== previous, beforePan)
  await touch.detach()
  await phone.getByRole('button', { name: '适应窗口', exact: true }).tap()
  for (const size of [{ width: 320, height: 568 }, { width: 390, height: 844 }, { width: 768, height: 1024 }, { width: 844, height: 390 }]) {
    await phone.setViewportSize(size)
    await mobileFits()
    const canvas = await phone.locator('.canvas-host:visible').boundingBox()
    const footer = await phone.locator('.export-bar').boundingBox()
    assert.ok(canvas.height >= 48 && canvas.y + canvas.height <= footer.y, 'Phone canvas must not be covered by the footer')
    await phone.screenshot({ path: resolve(output, `mobile-preview-${size.width}.png`) })
  }
  await phone.setViewportSize({ width: 390, height: 844 })
  await phone.getByRole('tab', { name: '设置', exact: true }).tap()
  await phone.getByRole('button', { name: '物品图标', exact: true }).tap()
