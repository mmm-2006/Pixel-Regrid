  assert.equal(await phone.getByRole('combobox', { name: '缩放算法' }).isVisible(), true)
  await phone.getByRole('button', { name: '透明噪点阈值说明', exact: true }).tap()
  assert.equal(await phone.getByRole('tooltip').isVisible(), true)
  await phone.getByRole('button', { name: '透明噪点阈值说明', exact: true }).tap()
  assert.equal(await phone.getByRole('tooltip').isVisible(), false)
  await mobileFits()
  await phone.screenshot({ path: resolve(output, 'mobile-settings.png') })
  await phone.getByRole('button', { name: '帮助', exact: true }).tap()
  const help = await phone.getByRole('dialog').boundingBox()
  assert.ok(help.x >= 0 && help.x + help.width <= 390 && help.y >= 0 && help.y + help.height <= 844, 'Phone help must fit in the viewport')
  await phone.getByRole('button', { name: '关闭弹窗', exact: true }).tap()
  await phone.getByRole('tab', { name: /^图片/ }).tap()
  await phone.getByRole('button', { name: '多选', exact: true }).tap()
  await phone.getByRole('listbox').getByRole('option').first().tap()
