  await phone.getByRole('button', { name: '适应窗口', exact: true }).tap()
  const touchCanvas = phone.locator('.canvas-host:visible canvas')
  const beforePan = await touchCanvas.evaluate(element => element.toDataURL())
  const touchBounds = await touchCanvas.boundingBox()
  const touch = await phone.context().newCDPSession(phone)
  const touchPoint = { x: touchBounds.x + touchBounds.width / 2, y: touchBounds.y + touchBounds.height / 2 }
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [touchPoint] })
