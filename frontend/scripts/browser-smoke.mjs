  const phoneChooser = phone.waitForEvent('filechooser')
  await phone.getByRole('button', { name: '添加图片', exact: true }).click()
  await (await phoneChooser).setFiles(resolve(root, ice.source))
  await phone.waitForFunction(() => document.querySelector('.preview-info')?.textContent.includes('网格 42×42'))
  assert.equal(await phone.getByRole('tab', { name: '预览', exact: true }).getAttribute('aria-selected'), 'true')
  assert.equal(await phone.locator('.image-pane:visible').count(), 1)
  await phone.getByRole('button', { name: '原图', exact: true }).tap()
  assert.ok((await phone.locator('.image-heading').filter({ visible: true }).textContent()).includes('1254 × 1254'))
  await phone.getByRole('button', { name: '结果', exact: true }).tap()
  assert.ok((await phone.locator('.image-heading').filter({ visible: true }).textContent()).includes('42 × 42'))
  const zoom = await phone.locator('.zoom-value').textContent()
